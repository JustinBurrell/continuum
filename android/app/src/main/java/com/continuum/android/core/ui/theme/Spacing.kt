package com.continuum.android.core.ui.theme

import androidx.compose.ui.unit.dp

/** 4dp grid system for consistent spacing throughout the app. */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 20.dp
    val xxl = 24.dp
    val xxxl = 32.dp
    val huge = 48.dp
    val screenH = 16.dp   // default horizontal screen padding
    val screenV = 16.dp   // default vertical screen padding
    val cardInner = 16.dp  // inner padding for cards
    val sectionGap = 24.dp // gap between major sections
}
